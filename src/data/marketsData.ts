export type TimeframeKey = '1D' | '5D' | '1M' | '6M' | 'YTD' | '1Y' | '5Y';

export type AssetCategory = 'index' | 'stock' | 'crypto';

export type BadgeTone =
  | 'error'
  | 'primary'
  | 'primary-container'
  | 'inverse'
  | 'secondary'
  | 'secondary-container'
  | 'tertiary'
  | 'tertiary-container'
  | 'surface-low'
  | 'surface-low-primary'
  | 'surface-high'
  | 'error-container';

export interface ChartPoint {
  label: string;
  value: number;
}

export interface TimeframeSeries {
  delta: string;
  positive: boolean;
  neutral?: boolean;
  points: ChartPoint[];
}

export interface MarketAsset {
  id: string;
  symbol: string;
  name: string;
  shortCode: string;
  badgeTone: BadgeTone;
  category: AssetCategory;
  region?: 'US' | 'World' | 'Crypto';
  exchange: string;
  price: string;
  numericPrice: number;
  currency?: string;
  changePct: string;
  numericChangePct: number;
  positive: boolean;
  neutral?: boolean;
  marketCap?: string;
  numericMarketCap?: number;
  volume?: string;
  open?: string;
  high?: string;
  low?: string;
  prevClose?: string;
  series?: Record<TimeframeKey, TimeframeSeries>;
}


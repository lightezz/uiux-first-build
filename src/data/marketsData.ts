export function generateAssetSeries(asset: MarketAsset): Record<TimeframeKey, TimeframeSeries> {
  if (asset.series) return asset.series;

  const base = asset.numericPrice || 100;
  const seed = asset.symbol.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const sign = asset.positive ? 1 : -1;

  const makeWeights = (len: number, spread: number, trendSign: number) => {
    const arr: number[] = [];
    for (let i = 0; i < len; i++) {
      const progress = i / Math.max(1, len - 1);
      const wave = Math.sin((i + seed) * 1.15) * (spread * 0.22);
      const startOffset = -trendSign * spread * (1 - progress);
      arr.push(1 + startOffset + (i === len - 1 ? 0 : wave));
    }
    arr[len - 1] = 1;
    return arr;
  };

  const formatDelta = (pct: number) => {
    const absVal = Math.abs((base * pct) / 100);
    const valStr = absVal >= 10 ? absVal.toFixed(2) : absVal.toFixed(4);
    const signChar = pct >= 0 ? '+' : '−';
    return `${signChar}${valStr} (${signChar}${Math.abs(pct).toFixed(2)}%)`;
  };

  const p1d = asset.neutral ? 0 : asset.numericChangePct;

  return buildSeries(
    base,
    {
      '1D': makeWeights(17, Math.max(0.004, Math.abs(p1d) / 100), asset.neutral ? 0 : sign),
      '5D': makeWeights(11, 0.025, sign),
      '1M': makeWeights(11, 0.06, sign),
      '6M': makeWeights(11, 0.14, 1),
      'YTD': makeWeights(11, 0.22, 1),
      '1Y': makeWeights(13, 0.28, 1),
      '5Y': makeWeights(9, 0.42, 1),
    },
    {
      '1D': { delta: asset.neutral ? '0.00 (0.00%)' : formatDelta(p1d), positive: asset.positive },
      '5D': { delta: formatDelta(p1d * 1.8 + 0.45), positive: p1d * 1.8 + 0.45 >= 0 },
      '1M': { delta: formatDelta(p1d * 2.5 + 2.1), positive: p1d * 2.5 + 2.1 >= 0 },
      '6M': { delta: formatDelta(11.4 + (seed % 7)), positive: true },
      'YTD': { delta: formatDelta(21.8 + (seed % 12)), positive: true },
      '1Y': { delta: formatDelta(26.5 + (seed % 15)), positive: true },
      '5Y': { delta: formatDelta(64.2 + (seed % 30)), positive: true },
    }
  );
}


export function getBadgeClasses(tone: BadgeTone): string {
  switch (tone) {
    case 'error':
      return 'bg-light-error text-light-on-error dark:bg-bearish dark:text-white';
    case 'primary':
      return 'bg-light-primary text-light-on-primary dark:bg-tv-blue dark:text-white';
    case 'primary-container':
      return 'bg-light-primary-container text-light-on-primary dark:bg-dark-primary-container dark:text-white';
    case 'inverse':
      return 'bg-light-inverse-surface text-light-inverse-on-surface dark:bg-dark-inverse-surface dark:text-dark-inverse-on-surface';
    case 'secondary':
      return 'bg-light-secondary text-light-on-secondary dark:bg-bullish dark:text-white';
    case 'secondary-container':
      return 'bg-light-secondary-container text-light-on-secondary-container dark:bg-dark-secondary-container dark:text-dark-on-secondary-container';
    case 'tertiary':
      return 'bg-light-tertiary text-light-on-tertiary dark:bg-dark-tertiary-container dark:text-dark-on-tertiary-container';
    case 'tertiary-container':
      return 'bg-light-tertiary-container text-light-on-tertiary-container dark:bg-dark-tertiary-container dark:text-dark-on-tertiary-container';
    case 'surface-low-primary':
      return 'bg-light-surface-container-low text-light-primary dark:bg-dark-surface-container-high dark:text-dark-primary';
    case 'surface-high':
      return 'bg-light-surface-container-high text-light-on-surface dark:bg-dark-surface-container-highest dark:text-dark-on-surface';
    case 'error-container':
      return 'bg-light-error-container text-light-on-error-container dark:bg-dark-error-container dark:text-dark-on-error-container';
    case 'surface-low':
    default:
      return 'bg-light-surface-container-low text-light-on-surface dark:bg-dark-surface-container-high dark:text-dark-on-surface';
  }
}
